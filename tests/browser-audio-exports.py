"""Real Chromium Web Audio + MediaRecorder acceptance, no synthetic backend."""
import os, json, pathlib
from playwright.sync_api import sync_playwright
BASE=os.getenv('HITORI_QA_URL','http://127.0.0.1:5174/patrol-retest-demo/')
OUT=pathlib.Path(os.getenv('HITORI_QA_OUTPUT','/workspace/patrol-retest-demo/evidence/audio')); OUT.mkdir(parents=True,exist_ok=True)
with sync_playwright() as p:
    browser=p.chromium.launch(executable_path=os.getenv('HITORI_CHROMIUM','/usr/bin/chromium'),headless=True,args=['--no-sandbox'])
    page=browser.new_page(viewport={'width':1365,'height':950},accept_downloads=True)
    errors=[]; page.on('pageerror',lambda error:errors.append(str(error)))
    page.goto(BASE+'#/room/studio'); page.locator('#studio-title').wait_for()
    page.get_by_role('button',name='复制此小节 ＋',exact=True).click()
    page.get_by_role('textbox',name='当前小节名称',exact=True).fill('主歌')
    page.get_by_role('button',name='吉他第2步',exact=True).click()
    with page.expect_download(timeout=45000) as info:
        page.get_by_role('button',name='导出原创编曲 WAV',exact=True).click()
    info.value.save_as(OUT/'arrangement.wav')
    page.get_by_role('button',name='播放并开启音效',exact=True).click()
    page.get_by_role('button',name='停止播放',exact=True).wait_for(timeout=45000)
    page.wait_for_timeout(1000)
    page.screenshot(path=str(OUT/'studio-desktop.png'),full_page=True)
    page.get_by_role('button',name='停止播放',exact=True).click()
    page.goto(BASE+'#/room/project'); page.locator('#project-title').wait_for()
    page.locator('.project-parts > div').nth(0).locator('select').select_option('draft')
    page.get_by_role('button',name='装入编曲',exact=True).click()
    page.get_by_label('使用项目内的吉他音色',exact=True).check()
    page.get_by_label('循环次数',exact=True).select_option('1')
    page.get_by_label('视频长度上限',exact=True).select_option('10')
    page.locator('#project-play').click()
    page.get_by_role('button',name='停止演出',exact=True).wait_for(timeout=45000)
    page.get_by_role('button',name='停止演出',exact=True).click()
    with page.expect_download(timeout=60000) as info:
        page.locator('#project-video-export').click()
    video_path=OUT/('concert.'+info.value.suggested_filename.split('.')[-1]); info.value.save_as(video_path)
    page.screenshot(path=str(OUT/'project-desktop.png'),full_page=True)
    page.get_by_label('视频方向',exact=True).select_option('portrait')
    with page.expect_download(timeout=60000) as portrait_info:
        page.locator('#project-video-export').click()
    portrait_path=OUT/('concert-portrait.'+portrait_info.value.suggested_filename.split('.')[-1]);portrait_info.value.save_as(portrait_path)
    # Test browser decoding/playback of the files actually generated by the UI.
    page.route('**/qa-arrangement.wav',lambda route:route.fulfill(path=str(OUT/'arrangement.wav'),content_type='audio/wav'))
    page.route('**/qa-concert',lambda route:route.fulfill(path=str(video_path),content_type='video/'+video_path.suffix[1:]))
    metadata=page.evaluate('''async()=>{const result={};for(const [key,src,tag] of [['audio','qa-arrangement.wav','audio'],['video','qa-concert','video']]){const element=document.createElement(tag);element.controls=true;element.src=new URL(src,location.href.split('#')[0]).href;document.body.append(element);await new Promise((resolve,reject)=>{element.onloadedmetadata=resolve;element.onerror=()=>reject(new Error(key+' decode failed'));});await element.play();await new Promise(resolve=>setTimeout(resolve,650));result[key]={duration:element.duration,currentTime:element.currentTime,paused:element.paused,width:element.videoWidth||0,height:element.videoHeight||0};element.pause();element.remove();}return result;}''')
    page.set_viewport_size({'width':390,'height':844});page.goto(BASE+'#/room/studio');page.locator('#studio-title').wait_for();page.screenshot(path=str(OUT/'studio-mobile.png'),full_page=True)
    assert page.evaluate('document.documentElement.scrollWidth<=innerWidth'), 'studio mobile overflow'
    assert not errors,errors
    assert metadata['audio']['currentTime']>0.2 and not metadata['audio']['paused']
    assert metadata['video']['currentTime']>0.2 and not metadata['video']['paused']
    assert 7.3<metadata['audio']['duration']<7.5
    assert 7.3<metadata['video']['duration']<7.7
    result={'metadata':metadata,'errors':errors,'files':[str(OUT/'arrangement.wav'),str(video_path),str(portrait_path)]}
    (OUT/'playback.json').write_text(json.dumps(result,ensure_ascii=False,indent=2));print(json.dumps(result,ensure_ascii=False))
    browser.close()
